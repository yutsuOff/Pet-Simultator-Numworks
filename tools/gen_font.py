#!/usr/bin/env python3
"""Generate anti-aliased bitmap fonts (4 bits of alpha per pixel) as C source.

PC-only tool. The generated file (src/generated/fonts.c) is committed, so building
the game does not require Python nor the font files.

Usage: python3 tools/gen_font.py [output.c]
Fonts: Inter (SIL Open Font License 1.1), https://rsms.me/inter/
"""
import sys
from PIL import Image, ImageDraw, ImageFont

INTER = "/usr/share/fonts/opentype/inter/"
FONTS = [
    # (C name, file, pixel size)
    ("font_small", INTER + "Inter-SemiBold.otf", 11),
    ("font_medium", INTER + "Inter-Bold.otf", 13),
    ("font_big", INTER + "InterDisplay-ExtraBold.otf", 19),
]
EXTRA = "éèêëàâäçùûüôöîïÉÈÊÀÂÇÔŒœ×·…★→"
CHARSET = sorted(set(chr(c) for c in range(32, 127)) | set(EXTRA), key=ord)


def build(cname, path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    glyphs, bitmap = [], bytearray()
    for ch in CHARSET:
        adv = int(round(font.getlength(ch)))
        bbox = font.getbbox(ch)  # relative to (0,0) = left/ascender
        x0, y0, x1, y1 = bbox
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        offset = len(bitmap)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
            px = img.load()
            for y in range(h):
                row = []
                for x in range(w):
                    row.append(min(15, (px[x, y] + 8) // 17))
                if len(row) % 2:
                    row.append(0)
                for i in range(0, len(row), 2):
                    bitmap.append((row[i] << 4) | row[i + 1])
        glyphs.append((ord(ch), w, h, x0, y0, adv, offset))
    out = []
    out.append(f"static const uint8_t {cname}_bitmap[{len(bitmap)}] = {{")
    for i in range(0, len(bitmap), 24):
        out.append("  " + ",".join(f"0x{b:02x}" for b in bitmap[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const glyph_t {cname}_glyphs[{len(glyphs)}] = {{")
    for cp, w, h, xo, yo, adv, off in glyphs:
        out.append(f"  {{0x{cp:04x}, {w}, {h}, {xo}, {yo}, {adv}, {off}}},")
    out.append("};")
    out.append(f"const font_t {cname} = {{{ascent + descent}, {ascent}, {len(glyphs)}, "
               f"{cname}_glyphs, {cname}_bitmap}};")
    return "\n".join(out), len(bitmap)


def main():
    dst = sys.argv[1] if len(sys.argv) > 1 else "src/generated/fonts.c"
    parts = ["/* Generated by tools/gen_font.py - do not edit.",
             " * Glyphs rendered from Inter (SIL Open Font License 1.1). */",
             '#include "../gfx/font.h"', ""]
    total = 0
    for cname, path, size in FONTS:
        src, n = build(cname, path, size)
        parts.append(src)
        parts.append("")
        total += n
    with open(dst, "w") as f:
        f.write("\n".join(parts))
    print(f"{dst}: {len(CHARSET)} glyphs x {len(FONTS)} fonts, {total} bytes of bitmaps")


if __name__ == "__main__":
    main()
