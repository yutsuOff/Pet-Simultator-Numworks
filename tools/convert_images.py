#!/usr/bin/env python3
"""Converts PNG images into C sprites for the game (PC-only tool).

Each image becomes a paletted sprite: up to 255 colors (RGB565) plus 4 bits of
alpha per palette entry, so soft edges stay smooth over any background.
Fully transparent pixels all share palette index 0.

The list of images is read from assets/sprites.txt, one per line:
    <C name> <path to png> [<width>x<height>]
If a size is given, the image is resized (keeping its aspect ratio, centered).

Usage: python3 tools/convert_images.py [assets/sprites.txt] [src/generated/sprites]
Produces sprites.c and sprites.h.
"""
import sys
import zlib
from PIL import Image


def load(path, size):
    img = Image.open(path).convert("RGBA")
    if size:
        w, h = size
        img.thumbnail((w, h), Image.LANCZOS)
        framed = Image.new("RGBA", (w, h), (0, 0, 0, 0))
        framed.alpha_composite(img, ((w - img.width) // 2, (h - img.height) // 2))
        img = framed
    return img


def to_key(r, g, b, a):
    a4 = min(15, (a + 8) // 17)
    if a4 == 0:
        return None
    rgb565 = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
    return (rgb565, a4)


def palettize(img, quantize=255 // 4):
    raw = img.tobytes()
    px = [tuple(raw[i:i + 4]) for i in range(0, len(raw), 4)]
    keys = [to_key(*p) for p in px]
    colors = sorted(set(k for k in keys if k))
    if len(colors) > 254:  # index 0 is transparent: at most 255 entries in all
        # Too many colors: quantize the RGB part, keep the alpha channel (fewer colors if the
        # alpha levels still make too many pairs).
        alpha = img.getchannel("A")
        rgb = img.convert("RGB").quantize(colors=quantize, method=Image.Quantize.MEDIANCUT).convert("RGB")
        rgb.putalpha(alpha)
        return palettize(rgb, quantize * 3 // 4)
    index = {c: i + 1 for i, c in enumerate(colors)}
    pixels = [index[k] if k else 0 for k in keys]
    return [(0, 0)] + colors, pixels


MAX_PACKED_PIXELS = 48 * 48  # SPRITE_MAX_PACKED_PIXELS in src/gfx/gfx.h


def sprite_c(name, img, storage="", packed=False):
    """C source of one sprite. Returns (lines, bytes of flash). A packed sprite keeps its
    pixels as raw DEFLATE data (decoded by src/gfx/inflate.c when drawn)."""
    palette, pixels = palettize(img)
    raw = len(pixels)
    if packed:
        if raw > MAX_PACKED_PIXELS:
            sys.exit(f"{name}: too big to be packed")
        z = zlib.compressobj(9, zlib.DEFLATED, -15, 9)
        data = z.compress(bytes(pixels)) + z.flush()
        assert zlib.decompress(data, -15) == bytes(pixels)
        pixels = list(data)
    c = [f"static const uint16_t {name}_pal[{len(palette)}] = {{"
         + ",".join(f"0x{p[0]:04x}" for p in palette) + "};",
         f"static const uint8_t {name}_alpha[{len(palette)}] = {{"
         + ",".join(str(p[1]) for p in palette) + "};",
         f"static const uint8_t {name}_px[{len(pixels)}] = {{"]
    for i in range(0, len(pixels), 32):
        c.append("  " + ",".join(str(v) for v in pixels[i:i + 32]) + ",")
    c.append("};")
    c.append(f"{storage}const sprite_t {name} = {{{img.width}, {img.height}, {len(palette)}, "
             f"{name}_pal, {name}_alpha, {name}_px, {len(pixels) if packed else 0}}};")
    c.append("")
    return c, len(pixels) + len(palette) * 3


def main():
    listing = sys.argv[1] if len(sys.argv) > 1 else "assets/sprites.txt"
    base = sys.argv[2] if len(sys.argv) > 2 else "src/generated/sprites"
    entries = []
    for line in open(listing):
        line = line.split("#")[0].strip()
        if not line:
            continue
        parts = line.split()
        size = tuple(int(v) for v in parts[2].split("x")) if len(parts) > 2 else None
        entries.append((parts[0], parts[1], size))

    c = ["/* Generated by tools/convert_images.py from assets/sprites.txt - do not edit. */",
         '#include "sprites.h"', ""]
    h = ["/* Generated by tools/convert_images.py - do not edit. */",
         "#ifndef GENERATED_SPRITES_H", "#define GENERATED_SPRITES_H", "",
         '#include "../gfx/gfx.h"', ""]
    total = 0
    for name, path, size in entries:
        lines, size = sprite_c(name, load(path, size))
        c += lines
        h.append(f"extern const sprite_t {name};")
        total += size
    h += ["", "#endif", ""]
    open(base + ".c", "w").write("\n".join(c))
    open(base + ".h", "w").write("\n".join(h))
    print(f"{base}.c: {len(entries)} sprites, {total} bytes")


if __name__ == "__main__":
    main()
